      NODE4=NODPLC(LOC+5)
      IBR1=NODPLC(LOC+8)
      IBR2=NODPLC(LOC+9)
      LOCY=LVN+NODPLC(LOC+10)
      VALUE(LOCY)=VALUE(LOCY)+Y0
      LOCY=LVN+NODPLC(LOC+11)
      VALUE(LOCY)=-Y0
      LOCY=LVN+NODPLC(LOC+12)
      VALUE(LOCY)=-1.0D0
      LOCY=LVN+NODPLC(LOC+13)
      VALUE(LOCY)=VALUE(LOCY)+Y0
      LOCY=LVN+NODPLC(LOC+14)
      VALUE(LOCY)=-1.0D0
      LOCY=LVN+NODPLC(LOC+15)
      VALUE(LOCY)=-Y0
      LOCY=LVN+NODPLC(LOC+16)
