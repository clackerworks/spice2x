  910 WRITE (IOFILE,911) TIME,DELTA,NUMNIT
  911 FORMAT(1H0,10X,'TIME = ',1PD12.5,';  DELTA = ',D12.5,';  NUMNIT =
     1',I6/)
      WRITE (IOFILE,916)
  916 FORMAT(1H0/'0LAST NODE VOLTAGES:'/)
      WRITE (IOFILE,AVHDR) (ANODE,AVLTG,I=1,NVPRLN)
