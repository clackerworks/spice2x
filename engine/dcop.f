      GO TO 130
  150 LOC=LOCATE(3)
  160 IF ((LOC.EQ.0).OR.(NODPLC(LOC+14).NE.0)) GO TO 300
      LOCV=NODPLC(LOC+1)
      IPTR=NODPLC(LOC+5)
      LOCT=NODPLC(LOC+11)
      IPOLY=NODPLC(LOC+4)
      IF (IPOLY.EQ.1) GO TO 170
      LCOEF=NODPLC(LOC+10)
      CALL SIZMEM(NODPLC(LOC+10),NCOEF)
  170 CIND=VALUE(LVNIM1+IPTR)
